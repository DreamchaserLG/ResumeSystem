-- Education reference data. Sources: MOE's 985/211 lists, 2022 Double First-Class
-- list and QS 2027 World University Rankings (published 2026-06-18).
-- Store only institution identity/location and overall ranks 1..100 (including ties).
-- Explicit aliases connect common Chinese/English names and official renames.
ALTER TABLE school ADD COLUMN location text;
CREATE TABLE school_world_rank (
    school_id bigint NOT NULL REFERENCES school(id) ON DELETE CASCADE,
    edition smallint NOT NULL,
    rank smallint NOT NULL CHECK (rank BETWEEN 1 AND 100),
    source text NOT NULL,
    PRIMARY KEY (school_id,edition)
);
ALTER TABLE school_world_rank ENABLE ROW LEVEL SECURITY;
ALTER TABLE school_world_rank FORCE ROW LEVEL SECURITY;
CREATE POLICY world_rank_read ON school_world_rank FOR SELECT TO rs_app USING (true);
GRANT SELECT ON school_world_rank TO rs_app;

