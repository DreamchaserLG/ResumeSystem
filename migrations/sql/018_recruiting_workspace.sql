CREATE FUNCTION workspace_monthly_salary(raw_label text, raw_value text)
RETURNS int LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE
    parts text[];
    amount int;
    upper_amount int;
    scale int;
    clean text := lower(regexp_replace(normalize(raw_value,NFKC),'[[:space:],，]','','g'));
BEGIN
    IF regexp_replace(normalize(raw_label,NFKC),'[[:space:]]','','g') !~ '^(期望薪资|期望薪酬|期望工资|薪资期望|期望月薪|期望待遇)$'
        OR (raw_label <> '期望月薪' AND clean !~ '(/月|每月|月薪|[k千])' )
        OR clean ~ '(年|美元|港币|欧元|usd|hkd)' THEN
        RETURN NULL;
    END IF;
    parts := regexp_match(clean,'^(?:月薪|人民币|rmb|¥)?([0-9]{1,6})([k千]?)(?:[-~—–至]([0-9]{1,6})([k千]?))?(?:元)?(?:/月|每月)?$');
    IF parts IS NULL THEN RETURN NULL; END IF;
    scale := CASE WHEN coalesce(nullif(parts[2],''),nullif(parts[4],'')) IS NOT NULL THEN 1000 ELSE 1 END;
    amount := parts[1]::int * scale;
    upper_amount := coalesce(parts[3],parts[1])::int * scale;
    IF amount <= 0 OR upper_amount < amount OR upper_amount > 1000000 THEN RETURN NULL; END IF;
    RETURN (amount + upper_amount) / 2;
END
$$;
